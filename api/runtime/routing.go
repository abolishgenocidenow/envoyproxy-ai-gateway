package runtime

import (
	"context"

	extprocv3 "github.com/envoyproxy/go-control-plane/envoy/service/ext_proc/v3"
	"google.golang.org/protobuf/types/known/structpb"
)

// ExtProcRouting replaces the complete Envoy routing handoff. Implementations
// must authenticate host context rather than trust client routing headers, honor
// cancellation, support concurrent requests, and never return secrets in metadata.
// Inputs are owned copies. Callbacks must not reenter the same request. Errors are
// sanitized. Nil preserves the upstream header/xDS strategy.
type ExtProcRouting interface {
	// Resolve runs once on the first request-headers message of each stream.
	// Downstream supplies Path. Upstream supplies RequestID, ConfigID, Backend and
	// Route from a trusted selection. It must not choose a newer config generation.
	Resolve(context.Context, *extprocv3.ProcessingRequest) (ExtProcRequest, error)
	// Handoff runs after downstream headers and after a successfully parsed body.
	// BodyReady distinguishes an absent model from the headers-only phase. Return
	// dynamic metadata (at most 64 KiB) for the host to propagate to Pick/Adapt.
	// Default internal routing headers and route-cache clearing are suppressed.
	Handoff(context.Context, RoutingHandoff) (*structpb.Struct, error)
}

// ExtProcRequest describes trusted stream identity. A downstream RequestID is
// generated by the server and reported through Handoff. Upstream Path, if set,
// must equal the original operation path. UpstreamHost is the trusted signing
// authority, independent of the logical Backend and the client :authority.
type ExtProcRequest struct {
	Upstream                                                bool
	RequestID, ConfigID, Path, Backend, Route, UpstreamHost string
}

// RoutingHandoff identifies the captured request and its configuration generation.
// ConfigID is an opaque serving generation, distinct from the source config UUID.
// ConfigUUID identifies the host-owned immutable source snapshot; hosts must
// use it to retain the matching Pick policy rather than their latest policy.
// It contains no credentials or request body. Retrying must preserve RequestID
// and ConfigID and supply a fresh backend selection to Resolve.
type RoutingHandoff struct {
	RequestID, ConfigID, ConfigUUID, Path, Model string
	BodyReady                                    bool
}
